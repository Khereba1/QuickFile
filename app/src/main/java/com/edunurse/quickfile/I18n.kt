    val frags: List<Pair<String, String>> = en.entries.map { it.key to it.value }.sortedByDescending { it.first.length }
}

fun tr(s: String): String {
    if (Prefs.lang != "en" || s.isEmpty() || !s.any { it in '\u0600'..'\u06FF' }) return s
    I18n.en[s]?.let { return it }
    var r = s
    for ((k, v) in I18n.frags) if (k in r) r = r.replace(k, v)
    return r
}

/** نفس Text بتاع Material لكن بيترجم أوتوماتيك. raw = true لأسماء الملفات والنصوص المستخرجة. */
@Composable
fun Text(
    text: String,
    modifier: Modifier = Modifier,
    color: Color = Color.Unspecified,
    fontSize: TextUnit = TextUnit.Unspecified,
    fontStyle: FontStyle? = null,
    fontWeight: FontWeight? = null,
    fontFamily: FontFamily? = null,
    letterSpacing: TextUnit = TextUnit.Unspecified,
    textDecoration: TextDecoration? = null,
    textAlign: TextAlign? = null,
    lineHeight: TextUnit = TextUnit.Unspecified,
    overflow: TextOverflow = TextOverflow.Clip,
    softWrap: Boolean = true,
    maxLines: Int = Int.MAX_VALUE,
    minLines: Int = 1,
    style: TextStyle = LocalTextStyle.current,
    raw: Boolean = false
) {
    M3Text(
        text = if (raw) text else tr(text), modifier = modifier, color = color, fontSize = fontSize, fontStyle = fontStyle,
        fontWeight = fontWeight, fontFamily = fontFamily, letterSpacing = letterSpacing, textDecoration = textDecoration,
        textAlign = textAlign, lineHeight = lineHeight, overflow = overflow, softWrap = softWrap, maxLines = maxLines,
        minLines = minLines, style = style
    )
}
